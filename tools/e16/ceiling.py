def patches(read_word):
    """read_word(va) -> original word; returns {va: (orig, new)} and asserts each old immediate"""
    out = {}
    for va, new in SITES.items():
        w = read_word(va)
        assert w & 0xffff == OLD_OF[new], 'ceiling site %x: %08x' % (va, w)
        out[va] = (w, (w & 0xffff0000) | new)
    return out


if __name__ == '__main__':
    import struct, subprocess, sys
    d = open(sys.argv[1], 'rb').read()
    rw = lambda va: struct.unpack_from('<I', d, va - 0x100000 + 0x80)[0]
    bad = 0
    for va in sorted(SITES):
        w = rw(va)
        ok = w & 0xffff == OLD_OF[SITES[va]]
        bad += not ok
        src = ' '.join('0x%02x' % b for b in struct.pack('<I', w))
        asm = subprocess.run(['llvm-mc', '--disassemble', '-triple=mipsel', '-mcpu=mips3'], input=src,
                             capture_output=True, text=True).stdout.split('\n')[1].strip()
        print('%x %08x %-28s -> %#x %s' % (va, w, asm, SITES[va], '' if ok else 'MISMATCH'))
    print(len(SITES), 'sites', bad, 'mismatches')
